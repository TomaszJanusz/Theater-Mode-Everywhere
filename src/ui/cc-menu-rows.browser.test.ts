import assert from 'node:assert/strict';
import { existsSync, readdirSync, readFileSync } from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { describe, it } from 'node:test';
import type { Browser } from 'playwright';
import { readStylesheet } from '../test-utils/styles';

const require = createRequire(import.meta.url);
const esbuild = require('esbuild') as { buildSync(options: object): { outputFiles: Array<{ text: string }> } };
const BUNDLE = esbuild.buildSync({
  stdin: { contents: "export { MediaFeaturesController } from './media-features/controller';", resolveDir: new URL('../', import.meta.url).pathname, loader: 'ts' },
  bundle: true, write: false, format: 'iife', globalName: 'CcMenu', platform: 'browser', target: 'es2022', logLevel: 'silent'
}).outputFiles[0].text;
const SRC = new URL('../', import.meta.url).pathname;
const UI_CSS = readStylesheet(path.join(SRC, 'ui/shadow.css'));
const LOCALES_DIR = path.join(SRC, '../_locales');
const LOCALES = readdirSync(LOCALES_DIR).sort();
const catalog = (locale: string): Record<string, string> => Object.fromEntries(
  Object.entries(JSON.parse(readFileSync(path.join(LOCALES_DIR, locale, 'messages.json'), 'utf8')) as Record<string, { message: string }>)
    .map(([key, entry]) => [key, entry.message]));
const english = catalog('en');

// Host track names are arbitrary: a short one, a long one and an unbroken one.
const TRACKS = [
  'English',
  'English (United States) - Closed captions for the deaf and hard of hearing, descriptive',
  'Przykładowa_bardzo_długa_nazwa_ścieżki_napisów_bez_żadnych_spacji_aby_wymusić_obcięcie'
];

async function withBrowser(engine: 'chromium' | 'firefox', run: (browser: Browser) => Promise<void>): Promise<void> {
  const browserType = (await import('playwright'))[engine];
  assert.ok(existsSync(browserType.executablePath()), `${engine} must be installed`);
  const browser = await browserType.launch({ headless: true });
  try { await run(browser); } finally { await browser.close(); }
}

describe('caption menu rows stay on one line', () => {
  for (const engine of ['chromium', 'firefox'] as const) {
    it(`fits every locale on one line in ${engine}`, { timeout: 120_000 }, async () => {
      await withBrowser(engine, async browser => {
        for (const viewport of [{ width: 360, height: 640 }, { width: 1280, height: 800 }]) {
          const page = await browser.newPage({ viewport });
          await page.setContent('<body style="margin:0"></body>');
          await page.addStyleTag({ content: UI_CSS });
          for (const locale of LOCALES) {
            const messages = { ...english, ...catalog(locale) };
            const labels = [messages.subtitlesOff, ...TRACKS, messages.autoGeneratedTrack.replace('$1', TRACKS[1])];
            const result = await page.evaluate(({ labels, title, options, dir }) => {
              document.body.replaceChildren();
              document.documentElement.dir = dir;
              document.body.innerHTML = `<div class="theater-controls-wrapper" dir="${dir}"><div style="display:flex;justify-content:flex-end">
                <div class="theater-cc-menu-host theater-menu-anchored is-open"><button type="button" class="theater-control-btn cc-btn"></button><div class="theater-cc-menu visible">
                  <div class="theater-cc-menu-header"><span class="theater-cc-menu-title"></span><button type="button" class="theater-cc-menu-options"></button></div>
                  <div class="theater-cc-menu-list"></div></div></div></div></div>`;
              document.querySelector('.theater-cc-menu-title')!.textContent = title;
              document.querySelector('.theater-cc-menu-options')!.textContent = options;
              const list = document.querySelector('.theater-cc-menu-list')!;
              labels.forEach((text, index) => {
                const item = document.createElement('button');
                item.className = 'theater-cc-menu-item' + (index === 1 ? ' active' : '');
                const label = document.createElement('span');
                label.className = 'theater-cc-menu-label';
                label.textContent = text;
                label.title = text;
                item.append(label);
                if (index === 1) {
                  const check = document.createElement('span');
                  check.className = 'theater-cc-menu-check';
                  check.textContent = '✓';
                  item.append(check);
                }
                list.append(item);
              });
              const menu = document.querySelector('.theater-cc-menu')!.getBoundingClientRect();
              const header = document.querySelector<HTMLElement>('.theater-cc-menu-header')!;
              return {
                width: menu.width, left: menu.left, right: menu.right, viewport: innerWidth,
                headerHeight: Math.round(header.getBoundingClientRect().height),
                // The header's own divider pseudo-element overhangs by a pixel, so compare the button instead.
                optionsInside: (() => {
                  const box = header.getBoundingClientRect();
                  const button = header.querySelector('button')!.getBoundingClientRect();
                  return button.left >= box.left - 0.5 && button.right <= box.right + 0.5;
                })(),
                rows: [...document.querySelectorAll<HTMLElement>('.theater-cc-menu-item')].map(row => ({
                  text: row.querySelector('.theater-cc-menu-label')!.textContent,
                  height: Math.round(row.getBoundingClientRect().height),
                  overflow: row.scrollWidth - row.clientWidth
                }))
              };
            }, { labels, title: messages.subtitlesMenuTitle, options: messages.subtitleOptions, dir: locale === 'ar' ? 'rtl' : 'ltr' });
            const context = `${engine} ${locale} ${viewport.width}px`;
            for (const row of result.rows) {
              assert.ok(row.height <= 30, `${context}: "${row.text}" wraps (${row.height}px)`);
              assert.ok(row.overflow <= 0, `${context}: "${row.text}" overflows by ${row.overflow}px`);
            }
            assert.ok(result.headerHeight <= 40, `${context}: header wraps (${result.headerHeight}px)`);
            assert.ok(result.optionsInside, `${context}: options button leaves the header`);
            assert.ok(result.left >= 0 && result.right <= result.viewport, `${context}: menu leaves the viewport (${result.left}..${result.right} of ${result.viewport})`);
            assert.ok(result.width <= 360 + 1, `${context}: menu exceeds its cap (${result.width}px)`);
          }
          await page.close();
        }
      });
    });
  }

  for (const engine of ['chromium', 'firefox'] as const) {
    it(`truncates long host track names rendered by the controller in ${engine}`, { timeout: 120_000 }, async () => {
      await withBrowser(engine, async browser => {
        const page = await browser.newPage({ viewport: { width: 360, height: 640 } });
        await page.setContent('<body style="margin:0"></body>');
        await page.addStyleTag({ content: UI_CSS });
        await page.evaluate('window.__name = value => value');
        await page.addScriptTag({ content: BUNDLE });
        const rows = await page.evaluate(({ tracks, messages }) => {
          document.body.innerHTML = '<div class="theater-controls-wrapper"><div style="display:flex;justify-content:flex-end"><div class="theater-cc-menu-host theater-menu-anchored is-open"><div class="theater-cc-menu visible"></div></div></div></div><div id="track"></div>';
          const noop = () => {};
          const controller = new (window as any).CcMenu.MediaFeaturesController({
            video: document.createElement('video'),
            ccBtn: document.createElement('button'),
            ccMenu: document.querySelector('.theater-cc-menu'),
            scrubberTrack: document.getElementById('track'),
            t: (key: string, ...subs: string[]) => (messages[key] ?? key).replace('$1', subs[0] ?? ''),
            renderer: { setCues: noop, update: noop, setStyle: noop, setMaxLines: () => false, dispose: noop },
            adapter: {
              probe: async () => ({ captions: true, chapters: false, previews: false }),
              listCaptionTracks: async () => [], getChapters: async () => [], dispose: noop,
              activateCaptionTrack: async () => ({ status: 'off', delivery: 'none', cues: [] })
            }
          });
          controller.tracks = tracks.map((label: string, index: number) => ({ id: `t${index}`, label, language: 'en', delivery: 'host' }));
          controller.renderCcMenu();
          return [...document.querySelectorAll<HTMLElement>('.theater-cc-menu-label')].map(label => ({
            text: label.textContent, title: label.title,
            overflowing: label.scrollWidth > label.clientWidth,
            ellipsis: getComputedStyle(label).textOverflow === 'ellipsis',
            height: Math.round(label.getBoundingClientRect().height)
          }));
        }, { tracks: TRACKS, messages: english });
        assert.equal(rows.length, TRACKS.length + 1);
        for (const row of rows) {
          assert.equal(row.title, row.text);
          assert.ok(row.ellipsis, `"${row.text}" lacks text-overflow: ellipsis`);
        }
        for (const long of rows.filter(row => TRACKS.slice(1).includes(row.text ?? ''))) {
          assert.ok(long.overflowing, `"${long.text}" is not truncated`);
          assert.ok(long.height <= 30, `"${long.text}" wraps`);
        }
        assert.equal(rows.find(row => row.text === 'English')?.overflowing, false);
        await page.close();
      });
    });
  }
});
