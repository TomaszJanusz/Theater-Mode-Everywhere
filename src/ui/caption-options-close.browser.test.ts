import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { existsSync } from 'node:fs';
import path from 'node:path';
import { describe, it } from 'node:test';
import type { Page } from 'playwright';
import { readStylesheet } from '../test-utils/styles';
import { ownTestBrowser } from '../test-utils/test-browser';

const require = createRequire(import.meta.url);
const SRC = new URL('../', import.meta.url).pathname;
const PAGE_CSS = readStylesheet(path.join(SRC, 'content.css'));
const UI_CSS = readStylesheet(path.join(SRC, 'ui/shadow.css'));
const esbuild = require('esbuild') as { buildSync(options: object): { outputFiles: Array<{ text: string }> } };
const BUNDLE = esbuild.buildSync({
  stdin: {
    contents: [
      "export { bootstrapPlayerRuntime } from './ui/player-runtime';",
      "export { setPlayerUiCss } from './ui/root';"
    ].join('\n'),
    resolveDir: SRC, loader: 'ts'
  },
  bundle: true, write: false, format: 'iife', globalName: 'CaptionOptionsTest',
  platform: 'browser', target: 'es2022', logLevel: 'silent'
}).outputFiles[0].text;

const FIXTURE = `<!doctype html><html><head><title>Caption options fixture</title>
  <style>body { margin:0; background:#111; } video { width:960px; height:540px; }</style>
  </head><body><video id="player" title="Caption loading regression" muted playsinline></video>
  <script>
    const canvas = document.createElement('canvas');
    canvas.width = 1280; canvas.height = 720;
    const ctx = canvas.getContext('2d');
    const gradient = ctx.createLinearGradient(0, 0, 1280, 720);
    gradient.addColorStop(0, '#1c2634'); gradient.addColorStop(1, '#0b1018');
    ctx.fillStyle = gradient; ctx.fillRect(0, 0, 1280, 720);
    ctx.strokeStyle = '#29384a'; ctx.lineWidth = 2;
    for (let x = 0; x < 1280; x += 80) { ctx.beginPath(); ctx.moveTo(x, 0); ctx.lineTo(x, 720); ctx.stroke(); }
    for (let y = 0; y < 720; y += 80) { ctx.beginPath(); ctx.moveTo(0, y); ctx.lineTo(1280, y); ctx.stroke(); }
    ctx.fillStyle = '#68788a'; ctx.font = '20px system-ui'; ctx.textAlign = 'center';
    ctx.fillText('LOCAL VIDEO FIXTURE', 640, 180);
    const video = document.querySelector('video');
    video.srcObject = canvas.captureStream(12);
    setInterval(() => { ctx.fillRect(0, 0, 1, 1); }, 100);
    video.play();
  </script></body></html>`;

/**
 * Starts the production player runtime with controlled extension settings and
 * enters theater mode on the fixture's playing video.
 * @param page Browser page containing the local video fixture.
 * @param host Host key used for the saved English caption preference.
 * @param saved Whether automatic caption restoration is enabled.
 * @returns When the theater controls have mounted.
 */
async function boot(page: Page, host: string, saved = true): Promise<void> {
  await page.evaluate(`window.chrome = { storage: {
    sync: {
      get: async () => ({ keepControlsVisible: true,
        captionPreferenceByHost: { [${JSON.stringify(host)}]: { enabled: ${saved}, language: 'en', autoGenerated: false } }
      }),
      set: async () => {}
    },
    onChanged: { addListener() {} }
  } };`);
  await page.addStyleTag({ content: PAGE_CSS });
  await page.addScriptTag({ content: BUNDLE });
  await page.evaluate(`CaptionOptionsTest.setPlayerUiCss(${JSON.stringify(UI_CSS)}); CaptionOptionsTest.bootstrapPlayerRuntime();`);
  await page.waitForFunction(() => document.querySelector('video')!.readyState >= 2);
  await page.keyboard.press('t');
  await page.locator('.theater-controls-wrapper').waitFor();
}

describe('caption options dialog close button', () => {
  for (const method of ['X button', 'Escape'] as const) {
    it(`closes with the ${method} like a dismissal, keeping playback and theater and restoring focus`, async t => {
      const { chromium } = await import('playwright');
      if (!existsSync(chromium.executablePath())) { t.skip('Chromium is not installed'); return; }
      const browser = await chromium.launch({ headless: true });
      ownTestBrowser(t, browser);
      try {
        const page = await browser.newPage({ viewport: { width: 1280, height: 800 } });
        await page.route('http://captions.test/**', async route => {
          const pathname = new URL(route.request().url()).pathname;
          if (pathname === '/en.vtt') await route.fulfill({ contentType: 'text/vtt', body: 'WEBVTT\n\n00:00:00.000 --> 00:01:00.000\nHello\n' });
          else await route.fulfill({ contentType: 'text/html', body: FIXTURE.replace('</video>', '<track kind="subtitles" label="English" srclang="en" src="/en.vtt"></video>') });
        });
        await page.goto('http://captions.test/');
        await boot(page, 'captions.test', false);
        const video = page.locator('video#player');
        const pausedBefore = await video.evaluate((v: HTMLVideoElement) => v.paused);
        await page.locator('.cc-btn').click();
        await page.locator('.theater-cc-menu-options').click();
        const dialog = page.locator('.theater-caption-options-dialog');
        await dialog.waitFor();
        const close = dialog.getByRole('button', { name: 'Close', exact: true });
        assert.equal(await close.count(), 1);
        assert.equal(await close.evaluate(button => button.classList.contains('theater-help-close-btn')), true, 'shares the Help close button styling');
        if (method === 'X button') await close.click();
        else await page.keyboard.press('Escape');
        await dialog.waitFor({ state: 'detached' });
        assert.equal(await video.evaluate((v: HTMLVideoElement) => v.paused), pausedBefore, 'playback is untouched');
        assert.equal(await page.locator('.theater-controls-wrapper').count(), 1, 'theater mode stays active');
        assert.equal(await page.locator('.te-dialog-overlay').count(), 0);
        assert.equal(await page.evaluate(() => document.body.classList.contains('te-dialog-open')), false);
        assert.equal(await page.locator('.cc-btn').evaluate(button => button.matches(':focus')), true, 'focus returns to the CC trigger');
      } finally { await browser.close(); }
    });
  }

  it('reaches the X button by keyboard and activates it with Enter', async t => {
    const { chromium } = await import('playwright');
    if (!existsSync(chromium.executablePath())) { t.skip('Chromium is not installed'); return; }
    const browser = await chromium.launch({ headless: true });
    ownTestBrowser(t, browser);
    try {
      const page = await browser.newPage({ viewport: { width: 1280, height: 800 } });
      await page.route('http://captions.test/**', async route => {
        const pathname = new URL(route.request().url()).pathname;
        if (pathname === '/en.vtt') await route.fulfill({ contentType: 'text/vtt', body: 'WEBVTT\n\n00:00:00.000 --> 00:01:00.000\nHello\n' });
        else await route.fulfill({ contentType: 'text/html', body: FIXTURE.replace('</video>', '<track kind="subtitles" label="English" srclang="en" src="/en.vtt"></video>') });
      });
      await page.goto('http://captions.test/');
      await boot(page, 'captions.test', false);
      await page.locator('.cc-btn').click();
      await page.locator('.theater-cc-menu-options').click();
      const dialog = page.locator('.theater-caption-options-dialog');
      await dialog.waitFor();
      await dialog.getByRole('button', { name: 'Close', exact: true }).focus();
      await page.keyboard.press('Enter');
      await dialog.waitFor({ state: 'detached' });
    } finally { await browser.close(); }
  });
});
