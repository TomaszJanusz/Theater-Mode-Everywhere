import assert from 'node:assert/strict';
import { describe, it } from 'node:test';

import { chromium, firefox, type Page } from 'playwright';

import { bootPlayer, enterTheater } from '../test-utils/player-boot';
import { sharedTestBrowser } from '../test-utils/test-browser';
import { testEngines } from '../test-utils/test-engines';
import { canvasVideoFixture } from '../test-utils/video-fixtures';

// While a caption track loads, the Subtitles row names the track beside the spinner, as soon as the load
// starts and from the same label the loaded row uses. The extension-less fixture serves two text tracks whose
// downloads the test holds, so the loading state can be read before the result replaces it.

const FIXTURE = canvasVideoFixture({ title: 'Caption language while loading' })
  .replace('</video>', '<track kind="subtitles" label="Polish" srclang="pl" src="/pl.vtt"><track kind="subtitles" label="German" srclang="de" src="/de.vtt"></video>');
const VTT = (text: string) => `WEBVTT\n\n00:00:00.000 --> 00:01:00.000\n${text}\n`;
const ROW = '.theater-everywhere-caption-hud [data-language-line="subtitles"]';

function gate() {
  let release!: () => void;
  const promise = new Promise<void>(resolve => { release = resolve; });
  return { promise, release };
}

const rowText = (page: Page) => page.locator(ROW).evaluate(node => [
  node.querySelector('.language-hud-label')!.textContent, node.querySelector('.language-hud-value')!.textContent]);
/** The live region is filled a moment after the notice paints. */
const spoken = async (page: Page, text: string) => {
  await page.waitForFunction(expected =>
    document.getElementById('theater-everywhere-ui')!.shadowRoot!.getElementById('theater-announcements')!.textContent === expected, text);
};

describe('caption language while loading', () => {
  for (const engine of testEngines()) {
    const shared = sharedTestBrowser(({ chromium, firefox })[engine]);

    it(`names the saved language while it restores and keeps the name when it loads in ${engine}`, { timeout: 60_000 }, async t => {
      const page = await (await shared.newContext(t, { viewport: { width: 1280, height: 800 } })).newPage();
      const holds = { pl: gate(), de: gate() };
      await page.route('http://captions.test/**', async route => {
        const name = new URL(route.request().url()).pathname.slice(1, 3) as keyof typeof holds;
        if (name in holds) {
          await holds[name].promise;
          await route.fulfill({ contentType: 'text/vtt', body: VTT(`Line in ${name}`) });
        } else await route.fulfill({ contentType: 'text/html', body: FIXTURE });
      });
      try {
        await page.goto('http://captions.test/');
        await bootPlayer(page, { settings: { keepControlsVisible: true, captionPreferenceByHost: { 'captions.test': { enabled: true, language: 'pl', autoGenerated: false } } } });
        await page.waitForFunction(() => document.querySelector('video')!.readyState >= 2);
        await enterTheater(page);

        await page.locator(`${ROW} .language-hud-spinner`).waitFor();
        assert.deepEqual(await rowText(page), ['Subtitles', 'Polish'], 'the restored language shows with the spinner, not a generic Loading');
        await spoken(page, 'Loading subtitles: Polish');
        const name = await page.locator(`${ROW} .language-hud-loading-text`).elementHandle();

        holds.pl.release();
        await page.locator('.language-hud-spinner').waitFor({ state: 'detached' });
        assert.deepEqual(await rowText(page), ['Subtitles', 'Polish']);
        assert.equal(await name!.evaluate(node => node.isConnected && node.className), 'language-hud-text', 'the same text stays, only the spinner leaves');
        await spoken(page, 'Subtitles: Polish');

        // A pick from the menu names its language the same way, and the result keeps it.
        await page.locator('.cc-btn').click();
        await page.getByRole('button', { name: 'German', exact: true }).click();
        await page.locator(`${ROW} .language-hud-spinner`).waitFor();
        assert.deepEqual(await rowText(page), ['Subtitles', 'German']);
        holds.de.release();
        await page.locator('.language-hud-spinner').waitFor({ state: 'detached' });
        assert.deepEqual(await rowText(page), ['Subtitles', 'German']);
      } finally { holds.pl.release(); holds.de.release(); }
    });
  }
});
