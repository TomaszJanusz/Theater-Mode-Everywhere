import assert from 'node:assert/strict';
import { describe, it, type TestContext } from 'node:test';

import type { Page } from 'playwright';

import { sharedEngineBrowsers } from '../test-utils/engine-browsers';
import { bootPlayer, enterTheater } from '../test-utils/player-boot';
import { testEngines } from '../test-utils/test-engines';
import { canvasVideoFixture, serveFixture } from '../test-utils/video-fixtures';

const browsers = sharedEngineBrowsers();
const HOST = 'player-boot.test';

/**
 * Gives the fixture video the `HTMLMediaElement.audioTracks` list that Safari ships and Chromium
 * and Firefox keep behind a flag: the generic path through the shared contract, menu and preference.
 */
const installAudioTracks = (tracks: Array<{ id: string; language: string; label: string; kind: string; enabled: boolean; refuse?: boolean }>) => {
  const video = document.querySelector('video')!;
  const list = new EventTarget() as EventTarget & Record<number, unknown> & { length: number };
  const changes: string[] = [];
  tracks.forEach((track, index) => {
    let enabled = track.enabled;
    list[index] = {
      ...track,
      get enabled() { return enabled; },
      set enabled(value: boolean) {
        // A track the host will not switch to, as a provider that cannot play it answers no.
        if (value === enabled || (value && track.refuse)) return;
        enabled = value;
        if (value) changes.push(track.id);
        queueMicrotask(() => list.dispatchEvent(new Event('change')));
      }
    };
  });
  list.length = tracks.length;
  Object.defineProperty(video, 'audioTracks', { value: list });
  Object.assign(window, { __audioChanges: changes, __enabled: () => tracks.map((_, index) => (list[index] as { enabled: boolean }).enabled) });
};

const DUBBED = [
  { id: 'en', language: 'en', label: 'English', kind: 'main', enabled: true },
  { id: 'fr', language: 'fr', label: 'Français', kind: 'translation', enabled: false },
  { id: 'de', language: 'de', label: 'Deutsch', kind: 'translation', enabled: false },
  { id: 'ad', language: 'en', label: 'English AD', kind: 'description', enabled: false }
];

async function open(test: TestContext, engine: 'chromium' | 'firefox', settings: Record<string, unknown>, tracks = DUBBED,
  subtitles?: Promise<void>): Promise<Page> {
  const page = await (await browsers[engine].newContext(test, { viewport: { width: 1280, height: 720 } })).newPage();
  const video = canvasVideoFixture({ title: 'Dubbed' });
  await serveFixture(page, subtitles ? video.replace('</video>', '<track kind="subtitles" label="English" srclang="en" src="/en.vtt"></video>') : video, `http://${HOST}/`);
  // Subtitles load only once theater turns them on; until `subtitles` settles, their spinner turns.
  if (subtitles) await page.route(`http://${HOST}/en.vtt`, async route => {
    await subtitles;
    await route.fulfill({ contentType: 'text/vtt', body: 'WEBVTT\n\n00:00:00.000 --> 00:10:00.000\nSubtitles from the saved language.\n' });
  });
  // tsx wraps named functions in __name(); the serialized fixture needs it before bootPlayer defines it.
  await page.addScriptTag({ content: 'window.__name = (fn) => fn;' });
  await page.evaluate(installAudioTracks, tracks);
  await bootPlayer(page, { settings });
  await page.waitForFunction(() => (document.querySelector('video')?.readyState ?? 0) >= 2);
  await enterTheater(page);
  return page;
}

const notice = (page: Page) => page.locator('.theater-everywhere-caption-hud');
/** Source and text of each line of the language notice, top to bottom, and how many plates show. */
const noticeLines = (page: Page) => page.evaluate(() => {
  const root = document.getElementById('theater-everywhere-ui')!.shadowRoot!;
  return {
    plates: root.querySelectorAll('.theater-everywhere-caption-hud').length,
    lines: [...root.querySelectorAll<HTMLElement>('.theater-everywhere-caption-hud [data-language-line]')]
      .map(line => [line.dataset.languageLine, line.querySelector('.volume-hud-text')?.textContent, line.querySelector('.volume-hud-detail')?.textContent ?? null])
  };
});
const announced = (page: Page) => page.evaluate(() => document.getElementById('theater-everywhere-ui')!.shadowRoot!.getElementById('theater-announcements')!.textContent);
const SAVED_ENGLISH_SUBTITLES = { captionPreferenceByHost: { [HOST]: { enabled: true, language: 'en', autoGenerated: false } } };
const LOCKED = [...DUBBED, { id: 'it', language: 'it', label: 'Italiano', kind: 'translation', enabled: false, refuse: true }];

/** A round trip to the page ends only after its pending microtasks, which is where a pick's answer continues. */
const settled = (page: Page) => page.evaluate(() => undefined);

/**
 * Enabling Français moves the item to another source in the same task, before the host's answer
 * reaches the player: the answer is for an item the viewer has already left.
 */
const leaveItemOnFrench = () => {
  const video = document.querySelector('video')!;
  const original = video.currentSrc;
  let source = original;
  Object.defineProperty(video, 'currentSrc', { get: () => source });
  const list = (video as unknown as { audioTracks: unknown }).audioTracks as EventTarget & Record<number, object>;
  const french = list[1];
  const descriptor = Object.getOwnPropertyDescriptor(french, 'enabled')!;
  Object.defineProperty(french, 'enabled', {
    get: descriptor.get,
    set(value: boolean) {
      descriptor.set!.call(french, value);
      if (value) {
        source = `${original}#next`;
        list.dispatchEvent(new Event('change'));
      }
    }
  });
};

const enabled = (page: Page) => page.evaluate(() => (window as unknown as { __enabled(): boolean[] }).__enabled());
const changes = (page: Page) => page.evaluate(() => (window as unknown as { __audioChanges: string[] }).__audioChanges);
const saved = (page: Page) => page.evaluate(async () => (await chrome.storage.sync.get('audioPreferenceByHost')).audioPreferenceByHost);
const row = (page: Page) => page.locator('.theater-settings-menu .audio-track-btn');
const rows = (page: Page) => page.locator('#theater-audio-track-list .theater-cc-menu-item');

async function openAudioMenu(page: Page): Promise<void> {
  await page.locator('.player-settings-btn').click();
  await row(page).click();
  await rows(page).first().waitFor();
}

describe('audio track menu and per-service preference', () => {
  for (const engine of testEngines()) {
    it(`applies this service's saved language once, and only this service's, in ${engine}`, async t => {
      const page = await open(t, engine, { audioPreferenceByHost: { [HOST]: 'fr', 'other.test': 'de' } });
      await page.waitForFunction(() => (window as unknown as { __audioChanges: string[] }).__audioChanges.length > 0);
      assert.deepEqual(await changes(page), ['fr']);
      assert.deepEqual(await enabled(page), [false, true, false, false]);

      const isolated = await open(t, engine, { audioPreferenceByHost: { 'other.test': 'de', 'youtube.com': 'original' } });
      await row(isolated).waitFor({ state: 'attached' });
      assert.deepEqual(await changes(isolated), [], 'another service\'s preference never applies');
    });

    it(`lists tracks, saves a pick for this service and resets it to the service default in ${engine}`, async t => {
      const page = await open(t, engine, {});
      await page.locator('.player-settings-btn').click();
      await assert.doesNotReject(row(page).waitFor());
      assert.equal(await row(page).getAttribute('aria-label'), 'Audio track: English, New', 'the row carries the 2.1 marker');
      await row(page).click();
      assert.deepEqual(await rows(page).evaluateAll(items => items.map(item => [item.textContent?.replace('✓', ''), item.getAttribute('aria-pressed')])),
        [['English', 'true'], ['Français', 'false'], ['Deutsch', 'false'], ['English AD', 'false']]);
      assert.equal(await page.locator('.theater-audio-track-reset').isHidden(), true, 'nothing saved, nothing to reset');

      // Keyboard and pointer share one path: arrows move, Enter picks, Escape goes back.
      await rows(page).first().focus();
      await page.keyboard.press('ArrowDown');
      await page.keyboard.press('Escape');
      assert.equal(await page.locator('.theater-settings-subview').isHidden(), true);
      assert.equal(await row(page).evaluate(element => element.matches(':focus')), true, 'Escape returns to the Audio track row');
      await page.keyboard.press('Enter');
      await rows(page).nth(2).focus();
      await page.keyboard.press('Enter');
      await page.waitForFunction(() => (window as unknown as { __audioChanges: string[] }).__audioChanges.includes('de'));
      assert.deepEqual(await enabled(page), [false, false, true, false]);
      await page.waitForFunction(async () => (await chrome.storage.sync.get('audioPreferenceByHost')).audioPreferenceByHost?.['player-boot.test'] === 'de');

      await openAudioMenu(page);
      await rows(page).nth(3).click();
      await page.waitForFunction(() => (window as unknown as { __audioChanges: string[] }).__audioChanges.includes('ad'));
      assert.deepEqual(await saved(page), { [HOST]: 'de' }, 'an audio description pick is not saved as the language');

      await openAudioMenu(page);
      const reset = page.locator('.theater-audio-track-reset');
      assert.equal(await reset.textContent(), 'Default');
      await reset.click();
      await page.waitForFunction(async () => !(await chrome.storage.sync.get('audioPreferenceByHost')).audioPreferenceByHost?.['player-boot.test']);
      assert.equal(await reset.isHidden(), true);
      assert.deepEqual(await enabled(page), [false, false, false, true], 'resetting keeps the current track');
    });

    it(`shows the settings button's New dot only while the hidden Audio track row is available in ${engine}`, async t => {
      const page = await open(t, engine, {}, DUBBED.slice(0, 1));
      const dot = page.locator('.player-settings-btn .te-new-badge');
      // Replaces the fixture's track list contents the way an adapter does when a video offers other tracks.
      const offer = (count: number) => page.evaluate(count => {
        const list = (document.querySelector('video') as unknown as { audioTracks: EventTarget & Record<number, unknown> & { length: number } }).audioTracks;
        for (let index = 0; index < 4; index++) {
          if (index < count) list[index] ??= { id: `t${index}`, language: 'en', label: `Track ${index}`, kind: index ? 'translation' : 'main', enabled: index === 0 };
          else delete list[index];
        }
        list.length = count;
        list.dispatchEvent(new Event(count > 1 ? 'addtrack' : 'removetrack'));
      }, count);
      await page.locator('.player-settings-btn').waitFor();
      assert.equal(await dot.count(), 0, 'a hidden row marks nothing');
      await offer(3);
      await dot.waitFor();
      assert.equal(await page.locator('.audio-track-btn .te-new-badge').count(), 1);
      await offer(1);
      await dot.waitFor({ state: 'detached' });
    });

    it(`hides the row with fewer than two tracks in ${engine}`, async t => {
      const page = await open(t, engine, { audioPreferenceByHost: { [HOST]: 'fr' } }, DUBBED.slice(0, 1));
      await page.locator('.player-settings-btn').click();
      await page.locator('.theater-settings-menu .help-btn').waitFor();
      assert.equal(await row(page).isHidden(), true);
      assert.deepEqual(await changes(page), []);
    });

    it(`joins the saved audio language to the turning subtitle spinner in one notice, then resolves it in ${engine}`, async t => {
      let release!: () => void;
      const subtitles = new Promise<void>(resolve => { release = resolve; });
      try {
        const page = await open(t, engine, { ...SAVED_ENGLISH_SUBTITLES, audioPreferenceByHost: { [HOST]: 'fr' } }, DUBBED, subtitles);
        await page.locator('.caption-hud-spinner').waitFor();
        await page.locator('[data-language-line="audio"]').waitFor();
        assert.deepEqual(await noticeLines(page), { plates: 1, lines: [
          ['subtitles', 'Loading subtitles...', null], ['audio', 'Audio track', 'Français']
        ] });
        release();
        await page.locator('.caption-hud-spinner').waitFor({ state: 'detached' });
        assert.deepEqual(await noticeLines(page), { plates: 1, lines: [
          ['subtitles', 'Subtitles on', 'English'], ['audio', 'Audio track', 'Français']
        ] }, 'the spinner resolved into the language and the audio line stayed');
        await page.waitForFunction(() => document.getElementById('theater-everywhere-ui')!.shadowRoot!.getElementById('theater-announcements')!.textContent
          === 'Subtitles on: English. Audio track: Français');
      } finally { release(); }
    });

    it(`adds a manual audio pick to the subtitles notice, and names the track when Default is chosen, in ${engine}`, async t => {
      const page = await open(t, engine, SAVED_ENGLISH_SUBTITLES, DUBBED, Promise.resolve());
      await page.locator('.theater-everywhere-caption-hud .volume-hud-detail', { hasText: 'English' }).waitFor();
      await openAudioMenu(page);
      await rows(page).nth(2).click();
      await page.locator('[data-language-line="audio"]', { hasText: 'Deutsch' }).waitFor();
      assert.deepEqual(await noticeLines(page), { plates: 1, lines: [
        ['subtitles', 'Subtitles on', 'English'], ['audio', 'Audio track', 'Deutsch']
      ] }, 'the audio pick joins the subtitles notice and replaces nothing');

      await openAudioMenu(page);
      await page.locator('.theater-audio-track-reset').click();
      await page.locator('[data-language-line="audio"]', { hasText: 'Deutsch (Default)' }).waitFor();
      assert.equal((await noticeLines(page)).plates, 1);
    });

    it(`names the saved language when it was already playing, and a refused pick as its own line, in ${engine}`, async t => {
      const page = await open(t, engine, { audioPreferenceByHost: { [HOST]: 'original' } }, LOCKED);
      await page.locator('[data-language-line="audio"]', { hasText: 'English' }).waitFor();
      assert.deepEqual(await changes(page), [], 'nothing switched');
      await openAudioMenu(page);
      await rows(page).nth(4).click();
      await page.locator('[data-language-line="audioRefused"]').waitFor();
      assert.deepEqual(await noticeLines(page), { plates: 1, lines: [
        ['audio', 'Audio track', 'English'], ['audioRefused', "Couldn't switch audio track", 'Italiano']
      ] });
      await page.waitForFunction(() => document.getElementById('theater-everywhere-ui')!.shadowRoot!.getElementById('theater-announcements')!.textContent
        === "Audio track: English. Couldn't switch audio track: Italiano");
      assert.equal(await announced(page), "Audio track: English. Couldn't switch audio track: Italiano");
      assert.deepEqual(await saved(page), { [HOST]: 'original' }, 'a refused pick saves nothing');
    });

    it(`stays silent when the host answers for an item the viewer has left, and leaves nothing on exit, in ${engine}`, async t => {
      const page = await open(t, engine, {});
      await page.evaluate(leaveItemOnFrench);
      await openAudioMenu(page);
      await rows(page).nth(1).click();
      await page.waitForFunction(() => (window as unknown as { __audioChanges: string[] }).__audioChanges.includes('fr'));
      await settled(page);
      assert.equal(await notice(page).count(), 0, 'the stale answer paints nothing');
      assert.deepEqual(await saved(page) ?? {}, {}, 'and saves nothing');

      await openAudioMenu(page);
      await rows(page).nth(2).click();
      await page.locator('[data-language-line="audio"]').waitFor();
      await page.keyboard.press('Escape');
      await page.locator('.theater-controls-wrapper').waitFor({ state: 'detached' });
      assert.equal(await notice(page).count(), 0, 'theater exit removes the notice');
    });
  }
});
