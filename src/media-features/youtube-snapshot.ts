import { sanitizeContentTitle } from './content-title';
import { findYoutubeChapterMarkers } from './parsers/youtube-chapters';
import { readYoutubePlayerMetadata, youtubeRecord } from './parsers/youtube-player-response';

export type YoutubeCaptionMeta = {
  id: string;
  language: string;
  label: string;
  kind: 'captions' | 'subtitles';
  autoGenerated: boolean;
  baseUrl: string;
};

export type YoutubePlayerSnapshot = {
  videoId?: string;
  title?: string;
  duration?: number;
  description?: string;
  captionTracks?: YoutubeCaptionMeta[];
  storyboardSpec?: string;
  markers?: Array<{ startMillis?: number; title?: { simpleText?: string } | string }>;
  heatmap?: {
    source: 'markers' | 'legacy' | 'svg';
    segments?: Array<{ startMs: number; durationMs: number; intensity: number }>;
    svgPath?: string;
    floor?: number;
  };
};

export const YOUTUBE_SNAPSHOT_SCRIPT_ID = 'theater-everywhere-youtube-snapshot';
export const YOUTUBE_CAPTION_AUTH_ID = 'theater-everywhere-youtube-caption-auth';

export function readPublishedYoutubeSnapshot(
  root: Pick<ParentNode, 'querySelector'> = document
): YoutubePlayerSnapshot | null {
  const el = root.querySelector(`#${YOUTUBE_SNAPSHOT_SCRIPT_ID}`);
  const text = el?.textContent || '';
  if (!text) return null;
  try {
    return normalizeYoutubeSnapshot(JSON.parse(text));
  } catch {
    return null;
  }
}

export function readPublishedYoutubeCaptionAuthUrls(
  root: Pick<ParentNode, 'querySelector'> = document
): string[] {
  const el = root.querySelector(`#${YOUTUBE_CAPTION_AUTH_ID}`);
  const text = el?.textContent || '';
  if (!text) return [];
  try {
    const data = JSON.parse(text);
    if (!Array.isArray(data)) return [];
    return data.filter((item): item is string => typeof item === 'string' && item.length > 0);
  } catch {
    return [];
  }
}

/**
 * @param strict Only snapshots naming `pageVideoId` qualify, and none while it is null: a video
 * parked in the miniplayer, where the page itself does not identify the content.
 */
export function firstMatchingYoutubeSnapshot(
  pageVideoId: string | null,
  candidates: Array<YoutubePlayerSnapshot | null | undefined>,
  strict = false
): YoutubePlayerSnapshot | null {
  let match: YoutubePlayerSnapshot | null = null;
  for (const snapshot of candidates) {
    if (!snapshot) continue;
    if (strict && (!pageVideoId || snapshot.videoId !== pageVideoId)) continue;
    if (snapshot.videoId && pageVideoId && snapshot.videoId !== pageVideoId) continue;
    if (!match) {
      match = snapshot;
      continue;
    }
    if (!match.videoId && pageVideoId && snapshot.videoId === pageVideoId) {
      match = {
        ...snapshot,
        heatmap: snapshot.heatmap?.segments?.length ? snapshot.heatmap : match.heatmap,
        title: snapshot.title || match.title
      };
      continue;
    }
    if (
      !match.heatmap?.segments?.length
      && snapshot.heatmap?.segments?.length
      && match.videoId
      && snapshot.videoId
      && match.videoId === snapshot.videoId
    ) {
      match = { ...match, heatmap: snapshot.heatmap };
    }
    if (
      !match.title
      && snapshot.title
      && (!match.videoId || !snapshot.videoId || match.videoId === snapshot.videoId)
    ) {
      match = { ...match, title: snapshot.title };
    }
  }
  return match;
}

// The boot script never changes after parsing, but SPA navigations and title updates read it
// again and again. Parse each script once; a length change means the parser was still
// appending its text.
const domSnapshots = new WeakMap<HTMLScriptElement, { length: number; snapshot: YoutubePlayerSnapshot | null }>();

export function readYoutubeSnapshotFromDom(): YoutubePlayerSnapshot | null {
  for (const script of document.querySelectorAll('script')) {
    const text = script.textContent || '';
    let parsed = domSnapshots.get(script);
    if (parsed?.length !== text.length) {
      parsed = { length: text.length, snapshot: parseYoutubeBootScript(text) };
      domSnapshots.set(script, parsed);
    }
    if (parsed.snapshot) return parsed.snapshot;
  }
  return null;
}

function parseYoutubeBootScript(text: string): YoutubePlayerSnapshot | null {
  if (!text.includes('ytInitialPlayerResponse')) return null;
  const match = text.match(/ytInitialPlayerResponse\s*=\s*(\{[\s\S]*?\});/);
  if (!match) return null;
  try {
    return normalizeYoutubePlayerResponse(JSON.parse(match[1]));
  } catch {
    return null;
  }
}

function normalizeYoutubeHeatmap(raw: unknown): YoutubePlayerSnapshot['heatmap'] | undefined {
  if (!raw || typeof raw !== 'object') return undefined;
  const data = raw as {
    source?: unknown;
    segments?: unknown;
    svgPath?: unknown;
    floor?: unknown;
  };
  const source = data.source;
  if (source !== 'markers' && source !== 'legacy' && source !== 'svg') return undefined;
  const segments = Array.isArray(data.segments)
    ? data.segments.flatMap((item) => {
      if (!item || typeof item !== 'object') return [];
      const row = item as { startMs?: unknown; durationMs?: unknown; intensity?: unknown };
      const startMs = typeof row.startMs === 'number' ? row.startMs : NaN;
      const durationMs = typeof row.durationMs === 'number' ? row.durationMs : NaN;
      const intensity = typeof row.intensity === 'number' ? row.intensity : NaN;
      if (!Number.isFinite(startMs) || !Number.isFinite(durationMs) || !Number.isFinite(intensity)) return [];
      if (startMs < 0 || durationMs <= 0) return [];
      return [{ startMs, durationMs, intensity }];
    })
    : undefined;
  const svgPath = typeof data.svgPath === 'string' && data.svgPath.trim().length > 20
    ? data.svgPath.trim()
    : undefined;
  const floor = typeof data.floor === 'number' ? data.floor : NaN;
  const usableFloor = Number.isFinite(floor) && floor > 0 && floor < 1 ? floor : undefined;
  if (!segments?.length && !svgPath) return undefined;
  return {
    source,
    ...(segments && segments.length > 0 ? { segments } : {}),
    ...(svgPath ? { svgPath } : {}),
    ...(usableFloor ? { floor: usableFloor } : {})
  };
}

export function normalizeYoutubePlayerResponse(raw: unknown): YoutubePlayerSnapshot | null {
  const metadata = readYoutubePlayerMetadata(raw);
  if (!metadata) return null;
  return {
    ...metadata,
    markers: findYoutubeChapterMarkers(raw),
    heatmap: normalizeYoutubeHeatmap(youtubeRecord(raw)?.heatmap)
  };
}

/** Validates the already-normalized DOM and event bridge snapshot separately from host responses. */
export function normalizeYoutubeSnapshot(raw: unknown): YoutubePlayerSnapshot | null {
  const data = youtubeRecord(raw);
  if (!data) return null;
  const captions: unknown[] = Array.isArray(data.captionTracks) ? data.captionTracks : [];
  const captionTracks = captions.slice(0, 40).flatMap((value, index): YoutubeCaptionMeta[] => {
    const track = youtubeRecord(value);
    if (!track || typeof track.baseUrl !== 'string' || !track.baseUrl || track.baseUrl.length > 32000) return [];
    const language = typeof track.language === 'string' ? track.language.slice(0, 16) : '';
    return [{
      id: typeof track.id === 'string' ? track.id.slice(0, 48) : `youtube:${language || index}`,
      language,
      label: typeof track.label === 'string' ? track.label.slice(0, 80) : language,
      kind: track.kind === 'captions' ? 'captions' : 'subtitles',
      autoGenerated: track.autoGenerated === true,
      baseUrl: track.baseUrl
    }];
  });
  return {
    videoId: typeof data.videoId === 'string' ? data.videoId.slice(0, 20) : undefined,
    title: sanitizeContentTitle(data.title) || undefined,
    duration: typeof data.duration === 'number' && Number.isFinite(data.duration) && data.duration > 0 ? data.duration : undefined,
    description: typeof data.description === 'string' ? data.description.slice(0, 20000) : undefined,
    captionTracks,
    storyboardSpec: typeof data.storyboardSpec === 'string' ? data.storyboardSpec.slice(0, 4000) : undefined,
    markers: findYoutubeChapterMarkers({ markersMap: [{ chapters: data.markers }] }),
    heatmap: normalizeYoutubeHeatmap(data.heatmap)
  };
}
