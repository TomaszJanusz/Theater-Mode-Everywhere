export type CaptionWord = {
  start: number;
  end: number;
  text: string;
};

export type CaptionCue = {
  start: number;
  end: number;
  text: string;
  words?: CaptionWord[];
};

export type CaptionActivationResult =
  | { status: 'active'; delivery: 'overlay'; cues: CaptionCue[] }
  | { status: 'active'; delivery: 'host'; cues: [] }
  | { status: 'off'; delivery: 'none'; cues: [] }
  | { status: 'failed'; delivery: 'none'; cues: [] };

/**
 * A deferred cue-window download invoked by the controller after it publishes
 * loading feedback. Creating the callback must not start network work.
 * @returns The provider's activation result for the requested caption window.
 */
export type CaptionCueRefresh = () => Promise<CaptionActivationResult>;

export type CaptionTrackSource =
  | 'native-text-track'
  | 'youtube'
  | 'vimeo'
  | 'dailymotion'
  | 'patreon'
  | 'twitch'
  | 'disney'
  | 'netflix'
  | 'bilibili'
  | 'bilibiliIntl'
  | 'tencent'
  | 'crunchyroll'
  | 'iqiyi'
  | 'viki';

export type CaptionTrack = {
  id: string;
  language: string;
  label: string;
  kind: 'captions' | 'subtitles';
  source: CaptionTrackSource;
  autoGenerated?: boolean;
  delivery?: 'overlay' | 'host';
  cues?: CaptionCue[];
};

export type Chapter = {
  start: number;
  end?: number;
  title: string;
  source: string;
  confidence: 'high' | 'medium';
};

export type PreviewFrame = {
  time: number;
  width: number;
  height: number;
  image: {
    kind: 'sprite';
    url: string;
    x: number;
    y: number;
    tileWidth: number;
    tileHeight: number;
    sheetWidth: number;
    sheetHeight: number;
  };
};

export type PreviewSource =
  | { kind: 'sprite'; provider: string }
  | { kind: 'none'; reason: string };

export type MediaCapabilities = {
  captions: boolean;
  chapters: boolean;
  previews: boolean;
};

/** Geometry supplied by a provider that paints its own captions. */
export type HostCaptionLayout = {
  width: number;
  height: number;
  lineHeight?: number;
  rows?: number;
  /** Optional element whose dock motion follows the shared caption policy. */
  motionTarget?: HTMLElement;
};

export interface HostCaptionLayoutSource {
  read(): HostCaptionLayout | null;
  observe?(onChange: () => void): () => void;
  reset?(): void;
}

export type TimelineHeatmap = {
  source: string;
  segments?: Array<{ startMs: number; durationMs: number; intensity: number }>;
  svgPath?: string;
};

export type AudioTrackKind = 'original' | 'dub' | 'description' | 'commentary' | 'unknown';

export type AudioTrack = {
  /** Opaque, stable for the media item; selection passes it back to the provider. */
  id: string;
  /** BCP-47 tag, or '' when the host gives none. */
  languageTag: string;
  label: string;
  kind: AudioTrackKind;
  selected: boolean;
  /** Retained knowledge whose live availability has not yet been revalidated. */
  disabled?: boolean;
};

/**
 * The audio tracks of one media item. `mediaId` names the item they describe (null when the
 * host has no identity for it), and `blocked` is true while the host plays something else in
 * the same player, such as an ad, during which a selection would not reach the content.
 */
export type AudioTrackList = {
  mediaId: string | null;
  tracks: readonly AudioTrack[];
  blocked: boolean;
  /** Keep retained tracks visible while blocked; commands and automatic picks stay disabled. */
  stale?: boolean;
  /** Optional command identity: a new binding retires picks without re-evaluating the title. */
  bindingId?: string;
};

export interface MediaFeaturesAdapter {
  readHostCaptionLayout?(): HostCaptionLayout | null;
  observeHostCaptionLayout?(onChange: () => void): () => void;
  probe(): Promise<MediaCapabilities>;
  listCaptionTracks(): Promise<CaptionTrack[]>;
  activateCaptionTrack(id: string | null): Promise<CaptionActivationResult>;
  /**
   * Determines whether the active track needs another cue window, without fetching it.
   * @param id Identifier of the active caption track.
   * @param time Display media time in seconds.
   * @returns A lazy download callback, or null synchronously when no work is needed.
   */
  prepareCaptionCueRefresh?(id: string, time: number): CaptionCueRefresh | null;
  getChapters?(): Promise<Chapter[]>;
  /**
   * Chapters the service's episode actions use even when another source owns the timeline, such as the host's
   * intro/outro windows. Null, like a missing method, leaves actions with the timeline's chapters.
   */
  getActionChapters?(): Promise<Chapter[] | null>;
  getHeatmap?(): TimelineHeatmap | null;
  getPreviewSource?(): Promise<PreviewSource>;
  getPreviewFrame?(time: number, duration: number): PreviewFrame | null;
  mediaId?(): string | null;
  getTitle?(): string | null;
  /** Reports title source changes; returns idempotent cleanup. */
  observeTitle?(onChange: () => void): () => void;
  /** Current tracks without side effects; null when this adapter offers none. Cheap enough to read on every change. */
  listAudioTracks?(): AudioTrackList | null;
  /**
   * Selects a track only if `mediaId` still names the current item and the track is still offered.
   * @returns Whether the host accepted the selection.
   */
  selectAudioTrack?(id: string, mediaId: string | null): Promise<boolean>;
  /** Reports track list, selection and blocking changes; returns idempotent cleanup. */
  observeAudioTracks?(onChange: () => void): () => void;
  /** Label shown beside this adapter's title, such as the episode. */
  getSubtitle?(): string | null;
  reload?(): Promise<void>;
  invalidate?(): void;
  dispose(): void;
}

/** Normalized positions in the shared scrubber, independent of media duration. */
export type TimelineMarker = {
  start: number;
  end: number;
  color: string;
  opacity: number;
  labelKey: string;
  textColor?: string;
};
export interface TimelineMarkerSource {
  observe(publish: (markers: readonly TimelineMarker[]) => void): () => void;
}
