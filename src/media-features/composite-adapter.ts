import { allSettledResults, fulfilledValues } from '../core/result';
import type {
  CaptionActivationResult,
  CaptionCueRefresh,
  CaptionTrack,
  Chapter,
  HostCaptionLayout,
  HostCaptionLayoutSource,
  MediaCapabilities,
  MediaFeaturesAdapter,
  PreviewFrame,
  PreviewSource,
  TimelineHeatmap
} from './types';

export function preferProviderCaptionTracks(tracks: CaptionTrack[]): CaptionTrack[] {
  const merged: CaptionTrack[] = [];
  const seen = new Set<string>();
  for (const track of tracks) {
    const key = `${track.source}:${track.language}:${track.label}:${track.autoGenerated ? 'auto' : 'manual'}`;
    if (seen.has(key)) continue;
    seen.add(key);
    merged.push(track);
  }
  if (merged.some((track) => track.source === 'patreon' || track.source === 'twitch' || track.source === 'disney' || track.source === 'netflix' || track.source === 'bilibili' || track.source === 'bilibiliIntl' || track.source === 'crunchyroll')) {
    return merged.filter((track) => track.source !== 'native-text-track');
  }
  return merged;
}

export class CompositeMediaAdapter implements MediaFeaturesAdapter {
  private adapters: MediaFeaturesAdapter[];
  private captionAdapter: MediaFeaturesAdapter | null = null;
  private captionTrackId: string | null = null;

  constructor(adapters: MediaFeaturesAdapter[], private hostCaptions: HostCaptionLayoutSource | null = null) {
    this.adapters = adapters;
  }

  readHostCaptionLayout(): HostCaptionLayout | null {
    if (this.hostCaptions) {
      try { return this.hostCaptions.read(); } catch { return null; }
    }
    for (const adapter of this.adapters) {
      try {
        const layout = adapter.readHostCaptionLayout?.();
        if (layout) return layout;
      } catch { /* A missing host renderer must not prevent another source. */ }
    }
    return null;
  }

  observeHostCaptionLayout(onChange: () => void): () => void {
    const cleanups: Array<() => void> = [];
    try {
      const hostCleanup = this.hostCaptions?.observe?.(onChange);
      if (hostCleanup) cleanups.push(hostCleanup);
    } catch { /* Caption observation is optional; keep other sources usable. */ }
    for (const adapter of this.adapters) {
      try {
        const cleanup = adapter.observeHostCaptionLayout?.(onChange);
        if (cleanup) cleanups.push(cleanup);
      } catch { /* Isolate a provider that cannot subscribe to its renderer. */ }
    }
    return () => {
      for (const cleanup of cleanups.splice(0)) {
        try { cleanup(); } catch { /* Disconnect every provider. */ }
      }
    };
  }

  /** Combines capabilities from adapters that respond successfully, ignoring rejected probes. */
  async probe(): Promise<MediaCapabilities> {
    const results = fulfilledValues(await allSettledResults(this.adapters.map((adapter) => adapter.probe())));
    return {
      captions: results.some((item) => item.captions),
      chapters: results.some((item) => item.chapters),
      previews: results.some((item) => item.previews)
    };
  }

  /**
   * Merges tracks from successful adapters and drops native tracks when a host
   * subtitle list is already present.
   */
  async listCaptionTracks(): Promise<CaptionTrack[]> {
    const lists = fulfilledValues(await allSettledResults(this.adapters.map((adapter) => adapter.listCaptionTracks())));
    return preferProviderCaptionTracks(lists.flat());
  }

  /**
   * Activates adapters that report the requested track and deactivates the others.
   * Passing `null` deactivates every adapter; failures are isolated so another adapter can respond.
   * @param id Requested track identifier, or null to disable all caption sources.
   * @returns The activation result, retaining its successful adapter for lazy cue refreshes.
   */
  async activateCaptionTrack(id: string | null): Promise<CaptionActivationResult> {
    this.captionAdapter = null;
    this.captionTrackId = null;
    if (id === null) {
      await allSettledResults(this.adapters.map((adapter) => adapter.activateCaptionTrack(null)));
      return { status: 'off', delivery: 'none', cues: [] };
    }
    let result: CaptionActivationResult = { status: 'failed', delivery: 'none', cues: [] };
    for (const adapter of this.adapters) {
      let tracks: CaptionTrack[] = [];
      try {
        tracks = await adapter.listCaptionTracks();
      } catch {
        continue;
      }
      try {
        if (tracks.some((track) => track.id === id)) {
          result = await adapter.activateCaptionTrack(id);
          this.captionAdapter = result.status === 'active' ? adapter : null;
          this.captionTrackId = result.status === 'active' ? id : null;
        } else {
          await adapter.activateCaptionTrack(null);
        }
      } catch {
        // A failing provider must not prevent native or other captions from activating (F-05).
      }
    }
    return result;
  }

  /**
   * Delegates window preparation to the adapter owning the active selection,
   * without rediscovering tracks or starting a download.
   * @param id Identifier of the active caption track.
   * @param time Display media time in seconds.
   * @returns A lazy provider request, or null for a mismatched track or a cached window.
   */
  prepareCaptionCueRefresh(id: string, time: number): CaptionCueRefresh | null {
    if (id !== this.captionTrackId) return null;
    return this.captionAdapter?.prepareCaptionCueRefresh?.(id, time) ?? null;
  }

  /** Returns the first nonempty chapter list, continuing past adapters that fail. */
  async getChapters(): Promise<Chapter[]> {
    return this.selectChapters();
  }

  async getChaptersForSource(source: string): Promise<Chapter[]> {
    return this.selectChapters(source);
  }

  private async selectChapters(source?: string): Promise<Chapter[]> {
    for (const adapter of this.adapters) {
      if (!adapter.getChapters) continue;
      try {
        const list = await adapter.getChapters();
        const chapters = source === undefined ? list : list.filter(chapter => chapter.source === source);
        if (chapters.length > 0) return chapters;
      } catch {
        // Keep looking; one provider's chapter failure is not fatal.
      }
    }
    return [];
  }

  /** Returns the first heatmap with a drawable path or segments. */
  getHeatmap(): TimelineHeatmap | null {
    for (const adapter of this.adapters) {
      if (!adapter.getHeatmap) continue;
      try {
        const heatmap = adapter.getHeatmap();
        if (heatmap?.svgPath || (heatmap?.segments && heatmap.segments.length > 0)) return heatmap;
      } catch {
        // Keep looking; a missing Most Replayed chart is not fatal.
      }
    }
    return null;
  }

  async getPreviewSource(): Promise<PreviewSource> {
    for (const adapter of this.adapters) {
      if (!adapter.getPreviewSource) continue;
      const source = await adapter.getPreviewSource();
      if (source.kind !== 'none') return source;
    }
    return { kind: 'none', reason: 'unsupported' };
  }

  getPreviewFrame(time: number, duration: number): PreviewFrame | null {
    for (const adapter of this.adapters) {
      const frame = adapter.getPreviewFrame?.(time, duration) || null;
      if (frame) return frame;
    }
    return null;
  }

  mediaId(): string | null {
    for (const adapter of this.adapters) {
      const id = adapter.mediaId?.();
      if (id) return id;
    }
    return null;
  }

  /**
   * Host adapters are registered after native, so the last nonempty title is the
   * provider currently reporting this playback.
   */
  getTitle(): string | null {
    let title: string | null = null;
    for (const adapter of this.adapters) {
      try {
        const next = adapter.getTitle?.()?.trim();
        if (next) title = next;
      } catch {
        // A provider that cannot name the video must not hide another provider's title.
      }
    }
    return title;
  }

  /** Reloads every adapter without rejecting when an individual reload fails. */
  async reload(): Promise<void> {
    await allSettledResults(this.adapters.map((adapter) => adapter.reload?.() ?? Promise.resolve()));
  }

  /**
   * Forgets caption ownership and resets host layout and adapter caches so
   * cue refreshes cannot target a selection from the previous lifecycle.
   */
  invalidate(): void {
    this.captionAdapter = null;
    this.captionTrackId = null;
    this.hostCaptions?.reset?.();
    this.adapters.forEach((adapter) => adapter.invalidate?.());
  }

  /**
   * Releases caption ownership, host layout state and every child adapter's resources.
   */
  dispose(): void {
    this.captionAdapter = null;
    this.captionTrackId = null;
    this.hostCaptions?.reset?.();
    this.adapters.forEach((adapter) => adapter.dispose());
  }
}
