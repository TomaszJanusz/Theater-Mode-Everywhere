/** What MAIN's harvest reports for the current page through the snapshot probe. */
export type TwitchCaptionMeta = {
  id: string;
  language: string;
  label: string;
  kind?: 'captions' | 'subtitles';
  url?: string;
  autoGenerated?: boolean;
  delivery?: 'overlay' | 'host';
};

export type TwitchPlayerSnapshot = {
  videoId?: string;
  title?: string;
  duration?: number;
  seekPreviewsURL?: string;
  moments?: Array<{ startTime?: number; endTime?: number; title?: string }>;
  captionTracks?: TwitchCaptionMeta[];
};

/** Window event after MAIN published new harvest metadata; the media controller refreshes on it. */
export const TWITCH_HARVEST_EVENT = 'theater-everywhere-twitch-harvest';

type Fields = Record<string, unknown>;
const fields = (value: unknown): Fields | null =>
  value && typeof value === 'object' && !Array.isArray(value) ? value as Fields : null;
const text = (value: unknown) => typeof value === 'string' ? value : undefined;
const finite = (value: unknown) => typeof value === 'number' && Number.isFinite(value) ? value : undefined;
const list = (value: unknown): Fields[] => Array.isArray(value)
  ? value.slice(0, 200).flatMap((item: unknown) => { const entry = fields(item); return entry ? [entry] : []; })
  : [];

/** The isolated adapter's reading of MAIN's probe entry: anything not shaped like a snapshot is dropped. */
export function parseTwitchSnapshot(value: unknown): TwitchPlayerSnapshot | null {
  const data = fields(value);
  if (!data) return null;
  return {
    videoId: text(data.videoId),
    title: text(data.title),
    duration: finite(data.duration),
    seekPreviewsURL: text(data.seekPreviewsURL),
    moments: list(data.moments).map(moment => ({ startTime: finite(moment.startTime), endTime: finite(moment.endTime), title: text(moment.title) })),
    captionTracks: list(data.captionTracks).flatMap(track => {
      const id = text(track.id);
      if (id === undefined) return [];
      const delivery = track.delivery === 'host' || track.delivery === 'overlay' ? track.delivery : undefined;
      return [{ id, language: text(track.language) ?? '', label: text(track.label) ?? '', url: text(track.url),
        autoGenerated: track.autoGenerated === true, delivery }];
    })
  };
}
