export type PatreonCaptionMeta = {
  id: string;
  language: string;
  label: string;
  kind?: 'captions' | 'subtitles';
  url: string;
  autoGenerated?: boolean;
};

export type PatreonPlayerSnapshot = {
  playbackId?: string;
  title?: string;
  duration?: number;
  storyboardUrl?: string;
  description?: string;
  chapters?: Array<{ startTime?: number; title?: string }>;
  captionTracks?: PatreonCaptionMeta[];
};

const text = (value: unknown, max: number): string | undefined => (typeof value === 'string' && value ? value.slice(0, max) : undefined);
const record = (value: unknown): Record<string, unknown> | null => (value !== null && typeof value === 'object' && !Array.isArray(value) ? value as Record<string, unknown> : null);

/**
 * The MAIN-world probe answers across the world boundary as plain data; the adapter validates it here
 * instead of trusting the shape. Caption URLs are still admitted by the fetch allowlist when fetched.
 */
export function normalizePatreonSnapshot(value: unknown): PatreonPlayerSnapshot | null {
  const raw = record(value);
  if (!raw) return null;
  const chapters = (Array.isArray(raw.chapters) ? raw.chapters : []).slice(0, 80).flatMap(item => {
    const chapter = record(item);
    return chapter && typeof chapter.startTime === 'number' && Number.isFinite(chapter.startTime) && typeof chapter.title === 'string'
      ? [{ startTime: chapter.startTime, title: chapter.title.slice(0, 120) }] : [];
  });
  const captionTracks = (Array.isArray(raw.captionTracks) ? raw.captionTracks : []).slice(0, 12).flatMap(item => {
    const track = record(item);
    const id = text(track?.id, 160);
    const url = text(track?.url, 2000);
    if (!track || !id || !url) return [];
    return [{
      id, url, language: text(track.language, 16) ?? '', label: text(track.label, 80) ?? '',
      kind: track.kind === 'captions' ? 'captions' as const : 'subtitles' as const,
      autoGenerated: track.autoGenerated === true
    }];
  });
  return {
    playbackId: text(raw.playbackId, 80),
    title: text(raw.title, 300),
    duration: typeof raw.duration === 'number' && Number.isFinite(raw.duration) ? raw.duration : undefined,
    storyboardUrl: text(raw.storyboardUrl, 2000),
    description: text(raw.description, 20000),
    chapters,
    captionTracks
  };
}
