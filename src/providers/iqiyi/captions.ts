import type { CaptionTrack, HostCaptionLayout } from '../../media-features/types';

/**
 * iq.com paints its own subtitles. The player's subtitle menu lists the languages the episode
 * offers and applies a choice itself, so tracks are read from that menu and selected by pressing
 * its item: the host keeps drawing and styling them (`delivery: 'host'`).
 */
const MENU = '.iqp-pop-subtitle-lang';
const ITEM = '.iqp-langlist-pop-txt';
const OFF_KEY = 'close';
const CUE = '.iqp-player [data-player-hook="subtitleelem"]';

/** The host's numeric language ids, as seen in its play-info `stl` entries. */
const LANGUAGES: Record<string, string> = {
  1: 'zh-Hans', 2: 'zh-Hant', 3: 'en', 4: 'ko', 5: 'ja', 6: 'fr', 18: 'th',
  21: 'ms', 23: 'vi', 24: 'id', 26: 'es', 27: 'pt', 28: 'ar'
};

export type IqiyiCaptionItem = { id: string; track: CaptionTrack; element: HTMLElement; selected: boolean };

export function trackId(languageId: string): string {
  return `iqiyi:${languageId}`;
}

function label(item: Element): string {
  const clone = item.cloneNode(true) as Element;
  clone.querySelectorAll('.iqp-langlist-source').forEach((node) => node.remove());
  return (clone.textContent ?? '').replace(/\s+/g, ' ').trim();
}

/** The subtitle menu only; the audio-language menu reuses the item class. */
function menuItems(doc: Document): HTMLElement[] {
  return [...doc.querySelectorAll(`${MENU} ${ITEM}`)].filter((item): item is HTMLElement => item instanceof HTMLElement);
}

export function readIqiyiCaptionItems(doc: Document): IqiyiCaptionItem[] {
  return menuItems(doc).flatMap((element) => {
    const languageId = element.getAttribute('datalid') ?? '';
    const name = label(element);
    if (element.getAttribute('datakey') === OFF_KEY || !/^\d{1,3}$/.test(languageId) || !name) return [];
    const id = trackId(languageId);
    const track: CaptionTrack = {
      id,
      language: LANGUAGES[languageId] ?? name,
      label: name,
      kind: 'subtitles',
      source: 'iqiyi',
      delivery: 'host',
      ...(element.querySelector('.iqp-langlist-source') ? { autoGenerated: true } : {})
    };
    return [{ id, track, element, selected: element.classList.contains('selected') }];
  });
}

/** Painted cue lines, so the shared dock can lift them above the control bar. */
export function readIqiyiCaptionLayout(doc: Document = document): HostCaptionLayout | null {
  let top = Infinity, bottom = -Infinity, left = Infinity, right = -Infinity, height = 0, lines = 0;
  for (const cue of doc.querySelectorAll(CUE)) {
    const rect = cue.getBoundingClientRect();
    if (rect.width <= 1 || rect.height <= 1) continue;
    top = Math.min(top, rect.top); bottom = Math.max(bottom, rect.bottom);
    left = Math.min(left, rect.left); right = Math.max(right, rect.right);
    height = Math.max(height, rect.height); lines++;
  }
  return lines ? { width: right - left, height: bottom - top, lineHeight: height, rows: lines } : null;
}
