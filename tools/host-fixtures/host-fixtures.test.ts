import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { describe, it } from 'node:test';

import collapsedJson from '../../test/host-fixtures/twitch-chat-collapsed.json';
import expandedJson from '../../test/host-fixtures/twitch-chat-expanded.json';

import { FIXTURE_BYTE_BUDGET, parseHostFixture, type HostFixture } from './format';
import type { RawNode } from './page-inspect';
import { RECIPES } from './recipes';
import { recordedMediaAdapter } from './recorded-adapter';
import { findLeaks, placeholder, sameShape, sanitizeMedia, sanitizeTree } from './sanitize';

// Every committed recording; a new one is imported here so the policy below covers it.
const COMMITTED: Record<string, unknown> = { 'twitch-chat-expanded': expandedJson, 'twitch-chat-collapsed': collapsedJson };

const raw = (tag: string, attrs: Record<string, string> = {}, children: RawNode[] = [], style = 'display:block;width:10px;height:10px'): RawNode => ({ tag, attrs, style, children });
const context = { identifying: ['SomeStreamer', 'My stream about things'], labels: ['Collapse Chat'], opaque: ['video-id'] };

describe('sanitizeTree', () => {
  it('keeps structure and drops content without a manual step', () => {
    const tree = sanitizeTree(raw('body', {}, [
      raw('div', { id: 'chat', class: 'chat-shell somestreamer-badge Layout-sc-1xcs6mc-0', 'data-a-target': 'right-column-chat-bar', 'aria-label': 'Collapse Chat', 'aria-hidden': 'true' }),
      raw('a', { id: 'user-12345', 'aria-label': 'Follow SomeStreamer', 'data-a-target': 'https://evil.test/x' }),
      raw('div', { 'video-id': 'AbC_12-xyZ9', hidden: 'until-found', role: 'complementary' }, [], 'display:block;background-image:url(https://cdn.test/a.png);width:5px')
    ]), context);
    assert.deepEqual(tree.children?.[0].attrs, { id: 'chat', class: 'chat-shell Layout-sc-1xcs6mc-0', 'data-a-target': 'right-column-chat-bar', 'aria-label': 'Collapse Chat', 'aria-hidden': 'true' });
    // A digit-bearing id is renumbered, a label the provider does not read keeps only its length.
    assert.deepEqual(tree.children?.[1].attrs, { id: 'fixture-id-1', 'aria-label': placeholder('Follow SomeStreamer') });
    assert.deepEqual(tree.children?.[2].attrs, { 'video-id': 'XxX_00-xxX0', role: 'complementary' });
    assert.equal(tree.children?.[2].style, 'display:block;width:5px');
    assert.equal(placeholder('Follow SomeStreamer').length, 'Follow SomeStreamer'.length);
  });

  it('keeps the shape of opaque ids so provider format checks still pass', () => {
    assert.equal(sameShape('dQw4w9WgXcQ'), 'xXx0x0XxXxX');
  });
});

describe('sanitizeMedia', () => {
  it('replaces free text, renumbers ids and keeps the shape', () => {
    const media = sanitizeMedia({
      title: 'My stream about things', subtitle: null, mediaId: 'v123456789',
      captionTracks: [{ id: 'https://cdn.test/en.vtt', language: 'en-US', label: 'English (CC by uploader)', kind: 'captions', autoGenerated: false }, { id: 'x', language: 'not a code', label: 'Mystery', kind: 'subtitles', autoGenerated: true }],
      chapters: [{ start: 12.4, end: 30.6, title: 'Intro with SomeStreamer' }]
    });
    assert.equal(media.title?.length, 'My stream about things'.length);
    assert.deepEqual(media.captionTracks.map(track => [track.id, track.language, track.label.length]), [['track-1', 'en-US', 24], ['track-2', 'und', 7]]);
    assert.deepEqual(media.chapters, [{ start: 12, end: 31, title: placeholder('Intro with SomeStreamer') }]);
    assert.equal(media.mediaId, 'x000000000');
  });
});

describe('findLeaks', () => {
  const fixture = parseHostFixture(expandedJson);
  it('finds a URL, token or identifying string anywhere, but not the host build id', () => {
    assert.deepEqual(findLeaks(fixture), []);
    const leaky: HostFixture = { ...fixture, dom: { tag: 'body', attrs: { class: 'x' }, children: [{ tag: 'div', attrs: { 'data-a-target': 'session-1f0e2d3c4b5a69788796a5b4' } }] }, media: fixture.media && { ...fixture.media, title: 'see https://x.test' } };
    assert.deepEqual(findLeaks(leaky), ['dom.children[0].attrs.data-a-target: hex token', 'media.title: url']);
    assert.deepEqual(findLeaks({ ...fixture, media: fixture.media && { ...fixture.media, title: 'by SomeStreamer' } }, ['somestreamer']), ['media.title: identifying string']);
  });
});

describe('committed host fixtures', () => {
  for (const [id, json] of Object.entries(COMMITTED)) {
    it(`${id} is valid, sanitized and within budget`, () => {
      const fixture = parseHostFixture(json);
      assert.equal(fixture.id, id);
      const recipe = RECIPES[id];
      assert.ok(recipe, `no recipe for ${id}`);
      assert.equal(fixture.service, recipe.service);
      assert.deepEqual(Object.keys(fixture.signature).sort(), Object.keys(recipe.probes).sort(), 'signature and recipe probes must match; recapture after changing probes');
      assert.match(fixture.capture.method, /tools\/host-fixtures\/test-utils\/capture\.ts/);
      assert.deepEqual(findLeaks(fixture), []);
      const bytes = Buffer.byteLength(`${JSON.stringify(fixture, null, 1)}\n`);
      assert.ok(bytes <= FIXTURE_BYTE_BUDGET, `${id} is ${bytes} bytes`);
    });
  }

  it('stay out of source archives', () => {
    assert.match(execFileSync('git', ['check-attr', 'export-ignore', 'test/host-fixtures'], { encoding: 'utf8' }), /export-ignore: set/);
  });

  it('rejects incomplete metadata', () => {
    const fixture = parseHostFixture(expandedJson);
    assert.throws(() => parseHostFixture({ ...fixture, capture: { ...fixture.capture, method: '' } }), /capture metadata/);
    assert.throws(() => parseHostFixture({ ...fixture, service: 'elsewhere' }), /service/);
    assert.throws(() => parseHostFixture({ ...fixture, format: 'te-host-fixture/0' }), /format/);
  });
});

describe('recordedMediaAdapter', () => {
  it('answers the provider contract from the recording', async () => {
    const fixture = parseHostFixture(expandedJson);
    const adapter = recordedMediaAdapter(fixture);
    assert.equal(adapter.getTitle?.(), fixture.media?.title);
    assert.deepEqual(await adapter.probe(), { captions: false, chapters: false, previews: false });
    assert.deepEqual(await adapter.activateCaptionTrack('missing'), { status: 'failed', delivery: 'none', cues: [] });
    const withTracks = recordedMediaAdapter({ ...fixture, media: { ...fixture.media!, captionTracks: [{ id: 'track-1', language: 'en', label: 'Recorded', kind: 'captions', autoGenerated: false }] } });
    assert.deepEqual((await withTracks.listCaptionTracks()).map(track => [track.id, track.source, track.delivery]), [['track-1', 'twitch', 'host']]);
    assert.deepEqual(await withTracks.activateCaptionTrack('track-1'), { status: 'active', delivery: 'host', cues: [] });
  });
});
