/**
 * Recorded host fixtures: a trimmed, sanitized fragment of a real host page plus provider-shaped
 * data, captured by `capture.ts` from the installed extension on a live page. They make fast tests
 * use realistic shapes; they never replace a check on the real host (docs/browser-tests.md, "Recorded host fixtures").
 */
export const FIXTURE_FORMAT = 'te-host-fixture/1';
/** One fragment, not a page: a capture over this fails instead of committing a page dump. */
export const FIXTURE_BYTE_BUDGET = 24 * 1024;
/** Services the extension already integrates; recordings are data about those providers only. */
export const FIXTURE_SERVICES = ['twitch'] as const;
export type FixtureService = (typeof FIXTURE_SERVICES)[number];

/** One element of the fragment. Text nodes are never recorded; layout is inlined in `style`. */
export interface FixtureNode {
  tag: string;
  attrs?: Record<string, string>;
  style?: string;
  children?: FixtureNode[];
}

/**
 * What the provider relies on, per probe (a named selector of the recipe): how many nodes match
 * (2 = several), whether the first one is laid out with a size, whether it is transformed, and
 * which other probes contain it. The nightly drift check compares this, not the markup.
 */
export interface ProbeState {
  count: 0 | 1 | 2;
  rendered: boolean;
  transformed: boolean;
  within: string[];
}
export type Signature = Record<string, ProbeState>;

export interface RecordedCaptionTrack {
  id: string;
  language: string;
  label: string;
  kind: 'captions' | 'subtitles';
  autoGenerated: boolean;
}
export interface RecordedChapter { start: number; end?: number; title: string }

/** Provider-shaped data, read through the installed extension's own MAIN-world probe. */
export interface RecordedMedia {
  title: string | null;
  subtitle: string | null;
  mediaId: string | null;
  captionTracks: RecordedCaptionTrack[];
  chapters: RecordedChapter[];
}
export interface RecordedPlayback { live: boolean; paused: boolean; muted: boolean; duration: number | null }

export interface HostFixture {
  format: typeof FIXTURE_FORMAT;
  /** Recipe id (`recipes.ts`) and file name. */
  id: string;
  service: FixtureService;
  capture: {
    date: string;
    extensionVersion: string;
    /** The host's own build id where it exposes one. */
    hostVersion: string | null;
    browser: string;
    /** How it was captured: tool, recipe, session state. Never the page URL. */
    method: string;
  };
  viewport: { width: number; height: number };
  signature: Signature;
  /** The `<body>` element, trimmed to the probes, their ancestors and a few descendants. */
  dom: FixtureNode;
  media: RecordedMedia | null;
  playback: RecordedPlayback | null;
}

const isRecord = (value: unknown): value is Record<string, unknown> => typeof value === 'object' && value !== null && !Array.isArray(value);
const fail = (id: string, what: string): never => { throw new Error(`host fixture ${id}: ${what}`); };
const isString = (value: unknown): value is string => typeof value === 'string';
const nullableString = (value: unknown): boolean => value === null || isString(value);

function checkNode(id: string, node: unknown, depth = 0): void {
  if (!isRecord(node) || !isString(node.tag) || !/^[a-z][a-z0-9-]*$/.test(node.tag)) fail(id, 'every node needs a lowercase tag');
  const { attrs, style, children } = node as Record<string, unknown>;
  if (depth > 60) fail(id, 'the fragment is nested too deeply');
  if (attrs !== undefined && (!isRecord(attrs) || !Object.values(attrs).every(isString))) fail(id, 'attrs must map names to strings');
  if (style !== undefined && !isString(style)) fail(id, 'style must be a string');
  if (children !== undefined) {
    if (!Array.isArray(children)) fail(id, 'children must be an array');
    for (const child of children as unknown[]) checkNode(id, child, depth + 1);
  }
}

function checkSignature(id: string, value: unknown): void {
  if (!isRecord(value) || !Object.keys(value).length) fail(id, 'signature must name at least one probe');
  for (const [name, state] of Object.entries(value as Record<string, unknown>)) {
    if (!isRecord(state) || ![0, 1, 2].includes(state.count as number) || typeof state.rendered !== 'boolean'
      || typeof state.transformed !== 'boolean' || !Array.isArray(state.within) || !state.within.every(isString)) {
      fail(id, `signature probe ${name} is malformed`);
    }
  }
}

function checkMedia(id: string, value: unknown): void {
  if (value === null) return;
  if (!isRecord(value) || !nullableString(value.title) || !nullableString(value.subtitle) || !nullableString(value.mediaId)
    || !Array.isArray(value.captionTracks) || !Array.isArray(value.chapters)) fail(id, 'media is malformed');
  const media = value as unknown as RecordedMedia;
  for (const track of media.captionTracks) {
    if (!isRecord(track) || !isString(track.id) || !isString(track.language) || !isString(track.label)
      || !['captions', 'subtitles'].includes(track.kind) || typeof track.autoGenerated !== 'boolean') fail(id, 'a caption track is malformed');
  }
  for (const chapter of media.chapters) {
    if (!isRecord(chapter) || typeof chapter.start !== 'number' || !isString(chapter.title)) fail(id, 'a chapter is malformed');
  }
}

/** Validates a parsed fixture file; tests, stories and the drift check all load through here. */
export function parseHostFixture(json: unknown): HostFixture {
  const id = isRecord(json) && isString(json.id) ? json.id : '(unknown)';
  if (!isRecord(json) || json.format !== FIXTURE_FORMAT) fail(id, `format must be ${FIXTURE_FORMAT}`);
  const fixture = json as Record<string, unknown>;
  if (!/^[a-z0-9][a-z0-9-]{0,59}$/.test(id)) fail(id, 'id must be kebab-case');
  if (!(FIXTURE_SERVICES as readonly unknown[]).includes(fixture.service)) fail(id, `service must be one of ${FIXTURE_SERVICES.join(', ')}`);
  const capture = fixture.capture;
  if (!isRecord(capture) || !isString(capture.date) || !/^\d{4}-\d{2}-\d{2}$/.test(capture.date)
    || !isString(capture.extensionVersion) || !nullableString(capture.hostVersion) || !isString(capture.browser)
    || !isString(capture.method) || !capture.method.trim()) fail(id, 'capture metadata needs date, extensionVersion, hostVersion, browser and method');
  const viewport = fixture.viewport;
  if (!isRecord(viewport) || typeof viewport.width !== 'number' || typeof viewport.height !== 'number') fail(id, 'viewport is malformed');
  checkSignature(id, fixture.signature);
  checkNode(id, fixture.dom);
  if ((fixture.dom as FixtureNode).tag !== 'body') fail(id, 'dom must be the body element');
  checkMedia(id, fixture.media);
  const playback = fixture.playback;
  if (playback !== null && (!isRecord(playback) || typeof playback.live !== 'boolean' || typeof playback.paused !== 'boolean'
    || typeof playback.muted !== 'boolean' || !(playback.duration === null || typeof playback.duration === 'number'))) fail(id, 'playback is malformed');
  return json as unknown as HostFixture;
}
