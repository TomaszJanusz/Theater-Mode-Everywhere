import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { parseArgs } from 'node:util';

import type { Page } from 'playwright';

import { parseTargets } from '../../live-e2e/config';
import { FIXTURE_BYTE_BUDGET, FIXTURE_FORMAT, parseHostFixture, type FixtureService, type HostFixture, type RecordedMedia, type RecordedPlayback } from '../format';
import { inspectScript, type PageInspection } from '../page-inspect';
import { recipeFor, type FixtureRecipe } from '../recipes';
import { BASE_ATTRIBUTES, findLeaks, sanitizeMedia, sanitizePlayback, sanitizeTree } from '../sanitize';

import { openRecipePage, withInstalledChromium } from './live';

// Usage: tsx tools/host-fixtures/test-utils/capture.ts <recipe> (--url <public page> | --page-type <LIVE_E2E_TARGETS id>)
//          [--extension dist/chrome-unpacked] [--out test/host-fixtures]
// Records one sanitized fragment and its provider data from the real host with the built extension
// installed (docs/browser-tests.md, "Recorded host fixtures"). Nothing it prints names the page.
const { values, positionals } = parseArgs({
  allowPositionals: true,
  options: { url: { type: 'string' }, 'page-type': { type: 'string' }, extension: { type: 'string', default: 'dist/chrome-unpacked' }, out: { type: 'string', default: 'test/host-fixtures' } }
});
const recipe = recipeFor(positionals[0] ?? '');
const url = values.url ?? parseTargets(process.env.LIVE_E2E_TARGETS).find(target => target.pageType === values['page-type'])?.url;
if (!url) throw new Error('pass --url <public page>, or --page-type with LIVE_E2E_TARGETS set');
const extensionDir = path.resolve(values.extension);
const versionOf = (file: string): string => (JSON.parse(readFileSync(file, 'utf8')) as { version: string }).version;
// Development builds stamp their own manifest version; record the release line it was built from too.
const manifestVersion = versionOf(path.join(extensionDir, 'manifest.json'));
const sourceVersion = versionOf(new URL('../../../package.json', import.meta.url).pathname);
const extensionVersion = manifestVersion === sourceVersion ? sourceVersion : `${sourceVersion} (build ${manifestVersion})`;

const isRecord = (value: unknown): value is Record<string, unknown> => typeof value === 'object' && value !== null && !Array.isArray(value);
const text = (value: unknown): string | null => (typeof value === 'string' && value.trim() ? value.trim() : null);

const list = (value: unknown): Array<Record<string, unknown>> => (Array.isArray(value) ? value.filter(isRecord) : []);
const track = (entry: Record<string, unknown>): RecordedMedia['captionTracks'][number] => ({
  id: String(entry.id), language: text(entry.language) ?? 'und', label: text(entry.label) ?? '', kind: entry.kind === 'subtitles' ? 'subtitles' : 'captions', autoGenerated: entry.autoGenerated === true
});
const markerTitle = (value: unknown): string => text(value) ?? (isRecord(value) ? text(value.simpleText) : null) ?? '';

/** Each service's probe snapshot (`src/media-features/probe.ts`) in the shared recorded shape. */
const MEDIA_FROM_PROBE: Record<FixtureService, (snapshot: Record<string, unknown>) => RecordedMedia> = {
  twitch: snapshot => ({
    title: text(snapshot.title),
    subtitle: null,
    mediaId: text(snapshot.videoId),
    captionTracks: list(snapshot.captionTracks).map(track),
    chapters: list(snapshot.moments).filter(moment => typeof moment.startTime === 'number')
      .map(moment => ({ start: moment.startTime as number, ...(typeof moment.endTime === 'number' ? { end: moment.endTime } : {}), title: text(moment.title) ?? '' }))
  }),
  youtube: snapshot => ({
    title: text(snapshot.title),
    subtitle: null,
    mediaId: text(snapshot.videoId),
    captionTracks: list(snapshot.captionTracks).map(track),
    chapters: list(snapshot.markers).filter(marker => typeof marker.startMillis === 'number')
      .map(marker => ({ start: (marker.startMillis as number) / 1000, title: markerTitle(marker.title) }))
  })
};

/** Asks the installed extension's MAIN-world probe, exactly as its isolated world does. */
async function probeMedia(page: Page, service: FixtureService): Promise<RecordedMedia | null> {
  const requestId = 1 + Math.floor(Math.random() * 1e9);
  await page.evaluate(id => {
    const target = window as unknown as { __teProbe?: unknown };
    window.addEventListener('theater-everywhere-media-probe-result', event => {
      const detail = (event as CustomEvent<{ requestId?: number }>).detail;
      if (detail?.requestId === id) target.__teProbe = detail;
    });
    window.dispatchEvent(new CustomEvent('theater-everywhere-media-probe', { detail: JSON.stringify({ requestId: id }) }));
  }, requestId);
  const detail = await (await page.waitForFunction(() => (window as unknown as { __teProbe?: unknown }).__teProbe, undefined, { timeout: 5000 })).jsonValue();
  const snapshot = isRecord(detail) ? detail[service] : null;
  return isRecord(snapshot) ? MEDIA_FROM_PROBE[service](snapshot) : null;
}

const readPlayback = (page: Page): Promise<RecordedPlayback | null> => page.evaluate(() => {
  const video = document.querySelector('video');
  if (!video) return null;
  const live = video.duration === Infinity;
  return { live, paused: video.paused, muted: video.muted, duration: live || !Number.isFinite(video.duration) ? null : video.duration };
});

async function capture(page: Page, target: string, from: FixtureRecipe): Promise<{ fixture: HostFixture; identifying: string[] }> {
  const { blocked } = await openRecipePage(page, target, from);
  if (blocked) throw new Error(`environment: ${blocked}; nothing recorded`);
  const inspection = await page.evaluate(inspectScript({ probes: from.probes, keepDepth: from.keepDepth, maxChildren: from.maxChildren, attributes: [...BASE_ATTRIBUTES, ...from.opaque] })) as PageInspection;
  const media = await probeMedia(page, from.service);
  const playback = await readPlayback(page);
  const hostVersion = from.hostVersion ? text(await page.evaluate(from.hostVersion)) : null;
  const browser = /Chrome\/([\d.]+)/.exec(await page.evaluate(() => navigator.userAgent))?.[1];
  const publicWords = new Set(from.publicWords.map(word => word.toLowerCase()));
  const identifying = [...inspection.identifying, media?.title ?? '', media?.subtitle ?? '', ...(media?.chapters.map(chapter => chapter.title) ?? [])]
    .filter(part => part.length >= 3 && !publicWords.has(part.toLowerCase()));
  const fixture: HostFixture = {
    format: FIXTURE_FORMAT,
    id: from.id,
    service: from.service,
    capture: {
      date: new Date().toISOString().slice(0, 10),
      extensionVersion,
      hostVersion: hostVersion && hostVersion.length <= 80 ? hostVersion : null,
      browser: browser ? `Chromium ${browser}` : 'Chromium',
      method: `tools/host-fixtures/test-utils/capture.ts ${from.id}: ${from.page}; installed unpacked Chromium build, fresh profile, automatic sanitization`
    },
    viewport: from.viewport,
    signature: inspection.signature,
    dom: sanitizeTree(inspection.dom, { identifying, labels: from.labels, opaque: from.opaque }),
    media: media && sanitizeMedia(media),
    playback: playback && sanitizePlayback(playback)
  };
  return { fixture: parseHostFixture(fixture), identifying };
}

async function main(): Promise<void> {
  const { fixture, identifying } = await withInstalledChromium(extensionDir, recipe.viewport, page => capture(page, url!, recipe));
  const leaks = findLeaks(fixture, identifying);
  if (leaks.length) throw new Error(`sanitization left identifying values at: ${leaks.join(', ')}; nothing written. Tighten the recipe or sanitize.ts.`);
  const json = `${JSON.stringify(fixture, null, 1)}\n`;
  const bytes = Buffer.byteLength(json);
  if (bytes > FIXTURE_BYTE_BUDGET) throw new Error(`${fixture.id} is ${bytes} bytes, over the ${FIXTURE_BYTE_BUDGET}-byte budget; lower keepDepth or maxChildren`);
  const file = path.resolve(values.out, `${fixture.id}.json`);
  writeFileSync(file, json);
  const missing = Object.entries(fixture.signature).filter(([, state]) => state.count === 0).map(([name]) => name);
  console.log(`wrote ${path.relative(process.cwd(), file)}: ${bytes} bytes, host ${fixture.capture.hostVersion ?? 'version unknown'}${missing.length ? `, probes absent: ${missing.join(', ')}` : ''}`);
}

void main().catch(error => { console.error(error instanceof Error ? error.message : String(error)); process.exitCode = 1; });
